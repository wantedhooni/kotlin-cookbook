CREATE TABLE deposit_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id VARCHAR(128) NOT NULL,
    external_account_id VARCHAR(128) NOT NULL,
    account_number_masked VARCHAR(128),
    product_name VARCHAR(255),
    product_type VARCHAR(128),
    currency VARCHAR(3),
    available_balance DECIMAL(19,4),
    raw_json TEXT NOT NULL,
    provider_updated_at TIMESTAMP WITH TIME ZONE,
    synced_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_deposit_account_party_external UNIQUE (party_id, external_account_id)
);

CREATE INDEX ix_deposit_account_party_id ON deposit_account (party_id);

CREATE TABLE idempotency_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation VARCHAR(80) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    http_status INTEGER,
    response_body TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_idempotency_operation_key UNIQUE (operation, idempotency_key)
);

CREATE INDEX ix_idempotency_expires_at ON idempotency_record (expires_at);

CREATE TABLE sync_lease (
    party_id VARCHAR(128) PRIMARY KEY,
    locked_until TIMESTAMP WITH TIME ZONE,
    locked_by VARCHAR(64),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
